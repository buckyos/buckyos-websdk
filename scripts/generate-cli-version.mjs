import { readFile, writeFile } from 'node:fs/promises'

const packageJson = JSON.parse(
  await readFile(new URL('../package.json', import.meta.url), 'utf8'),
)
if (
  !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(
    packageJson.version,
  )
) {
  throw new Error(
    `package version cannot be emitted safely: ${packageJson.version}`,
  )
}
const output = `// Generated by scripts/generate-cli-version.mjs. Do not edit.\n` +
  `export const PACKAGE_VERSION = '${packageJson.version}'\n` +
  `export const TOOL_VERSION = PACKAGE_VERSION\n` +
  `export const SDK_VERSION = PACKAGE_VERSION\n` +
  `export const PROTOCOL_VERSION = '1'\n`
await writeFile(new URL('../cli/version.ts', import.meta.url), output)
