async function rejects(t: Tap, promise: Promise<unknown>, kind: string): Promise<void> {
    let error: unknown = null
    try {
        await promise
    } catch (e) {
        error = e
    }
    t.eq(error instanceof NdnError ? error.kind : String(error), kind)
}

