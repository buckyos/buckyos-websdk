function buildRustFixtureCases(): NdnTypesTestCase[] {
    if (!Array.isArray(ndnObjectFixture)) {
        return [
            {
                name: 'rust fixture: tests/ndn_object.json must be an array',
                run() {
                    throw new Error(
                        `expected ndn_object.json to be an array, got ${typeof ndnObjectFixture}`,
                    )
                },
            },
        ]
    }

    const cases: NdnTypesTestCase[] = []

    // Aggregate "all entries verify" check — fast feedback when bulk-loading.
    // Uses the stricter decode → re-encode helper, so all 8 fixture object
    // types go through the SDK decoders.
    cases.push({
        name: 'rust fixture: every entry verifies via verifyNamedObjectByDecode',
        run(t) {
            t.deepEq(
                ndnObjectFixture.map(entry => entry.objid.split(':')[0]).sort(),
                ['cyact', 'cyfile', 'cyinc', 'cymsg', 'cypath', 'cyrece', 'cyrel', 'pkg'],
                'fixture object types',
            )
            for (const raw of ndnObjectFixture) {
                const entry = raw as { objid?: unknown; objjson?: unknown }
                t.truthy(
                    typeof entry.objid === 'string',
                    `entry missing objid: ${JSON.stringify(entry)}`,
                )
                t.truthy(
                    entry.objjson != null && typeof entry.objjson === 'object',
                    `entry missing objjson: ${JSON.stringify(entry)}`,
                )
                const expected = ObjId.fromString(entry.objid as string)
                const ok = verifyNamedObjectByDecode(expected, entry.objjson)
                if (!ok) {
                    // Recompute to surface the actual hash for easier triage.
                    const [actual, canonical] = buildNamedObjectByJson(
                        expected.objType,
                        entry.objjson,
                    )
                    throw new Error(
                        `rust fixture mismatch for ${expected.toString()}\n` +
                            `  computed: ${actual.toString()}\n` +
                            `  canonical: ${canonical}`,
                    )
                }
            }
        },
    })

    // Per-entry case so jest reports each ObjId individually on failure.
    for (const raw of ndnObjectFixture) {
        const entry = raw as { objid?: unknown; objjson?: unknown }
        if (typeof entry.objid !== 'string' || entry.objjson == null) continue
        const objIdStr = entry.objid
        const objJson = entry.objjson
        cases.push({
            name: `rust fixture: ${objIdStr}`,
            run(t) {
                const expected = ObjId.fromString(objIdStr)
                const [actual, canonical] = buildNamedObjectByJson(
                    expected.objType,
                    objJson,
                )
                t.eq(
                    actual.toString(),
                    expected.toString(),
                    `canonical=${canonical}`,
                )
                t.eq(verifyNamedObjectByDecode(expected, objJson), true)
            },
        })
    }

    return cases
}

// ============================================================
// Standalone runner (used by the browser test page)
// ============================================================

export interface NdnTypesRunResult {
    name: string
    ok: boolean
    error?: string
}

export async function runNdnTypesCases(
    cases: NdnTypesTestCase[] = NDN_TYPES_TEST_CASES,
    tap: Tap = defaultTap,
): Promise<{ ok: boolean; total: number; failed: number; results: NdnTypesRunResult[] }> {
    const results: NdnTypesRunResult[] = []
    let failed = 0
    for (const c of cases) {
        try {
            await c.run(tap)
            results.push({ name: c.name, ok: true })
        } catch (e) {
            failed++
            results.push({
                name: c.name,
                ok: false,
                error: (e as Error)?.message ?? String(e),
            })
        }
    }
    return { ok: failed === 0, total: cases.length, failed, results }
}
