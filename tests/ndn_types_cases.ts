// ============================================================
// Tap — minimal cross-runtime assertion interface
// ============================================================

export interface Tap {
    /** Strict (===) equality. */
    eq<T>(actual: T, expected: T, msg?: string): void
    /** Structural (recursive value) equality. */
    deepEq(actual: unknown, expected: unknown, msg?: string): void
    /** Asserts !!value. */
    truthy(value: unknown, msg?: string): void
    /** Asserts !value. */
    falsy(value: unknown, msg?: string): void
    /** Asserts value === null. */
    isNull(value: unknown, msg?: string): void
    /**
     * Asserts that fn() throws. If `kind` is provided, it must equal the
     * thrown NdnError's `kind` property.
     */
    throws(fn: () => unknown, kind?: string, msg?: string): void
}

export interface NdnTypesTestCase {
    name: string
    run(t: Tap): void | Promise<void>
}

// Default tap implementation: throws plain Errors with descriptive messages.
// Both jest and the browser runner can use this directly; jest's failure
// messages are slightly less rich than native expect() (no diff output) but
// the test names + messages still pinpoint the failure.
function fmt(value: unknown): string {
    if (value instanceof Uint8Array) {
        return `Uint8Array[${Array.from(value).join(',')}]`
    }
    try {
        return JSON.stringify(value)
    } catch {
        return String(value)
    }
}

function deepEqual(a: unknown, b: unknown): boolean {
    if (a === b) return true
    if (a === null || b === null) return false
    if (typeof a !== typeof b) return false
    if (typeof a !== 'object') return false
    if (a instanceof Uint8Array || b instanceof Uint8Array) {
        if (!(a instanceof Uint8Array) || !(b instanceof Uint8Array)) return false
        if (a.length !== b.length) return false
        for (let i = 0; i < a.length; i++) {
            if (a[i] !== b[i]) return false
        }
        return true
    }
    if (Array.isArray(a) || Array.isArray(b)) {
        if (!Array.isArray(a) || !Array.isArray(b)) return false
        if (a.length !== b.length) return false
        for (let i = 0; i < a.length; i++) {
            if (!deepEqual(a[i], b[i])) return false
        }
        return true
    }
    const ao = a as Record<string, unknown>
    const bo = b as Record<string, unknown>
    const ak = Object.keys(ao)
    const bk = Object.keys(bo)
    if (ak.length !== bk.length) return false
    for (const k of ak) {
        if (!Object.prototype.hasOwnProperty.call(bo, k)) return false
        if (!deepEqual(ao[k], bo[k])) return false
    }
    return true
}

// ============================================================
// Test-local strict verification: decode → re-encode → compare hash.
// ============================================================
//
// The SDK's `verifyNamedObject` is intentionally shape-agnostic: it
// canonicalizes whatever JSON value you hand it and compares the hash
// against the given ObjId. That's the right contract for the library
// (callers may be working with object types the SDK has no TS class for).
//
// For the test suite we want a stronger invariant on every NamedObject
// whose TS class the SDK ships: the raw JSON must survive a full
// decode → re-encode (`toJSON()`) round-trip and STILL hash to the
// expected ObjId. That way regressions like
//   - `static fromJSON` silently dropping a field
//   - `toJSON` emitting a field in a way that doesn't match what the
//     Rust reference impl wrote
// show up as test failures instead of slipping through a pure
// canonical-on-raw hash check.
//
// For an object type without a registered decoder, the helper falls back to
// the SDK's `verifyNamedObject`. The Rust fixture has none of those left.

type ObjIdProducer = { genObjId(): [ObjId, string] }
type NamedObjectDecoder = (raw: unknown) => ObjIdProducer

function asJsonObject(raw: unknown, ctx: string): Record<string, unknown> {
    if (raw == null || typeof raw !== 'object' || Array.isArray(raw)) {
        throw new NdnError(
            'InvalidData',
            `${ctx}: expected JSON object, got ${Array.isArray(raw) ? 'array' : typeof raw}`,
        )
    }
    return raw as Record<string, unknown>
}

// MsgObject, ReceiptObj, ActionObject and PackageMeta are plain JSON with
// decoding functions rather than classes.
function plainObjectProducer(objType: string, value: unknown): ObjIdProducer {
    return { genObjId: () => buildNamedObjectByJson(objType, value) }
}

const TEST_NAMED_OBJECT_DECODERS: Record<string, NamedObjectDecoder> = {
    [OBJ_TYPE_FILE]: raw => FileObject.fromJSON(asJsonObject(raw, 'FileObject.fromJSON')),
    [OBJ_TYPE_PATH]: raw => PathObject.fromJSON(asJsonObject(raw, 'PathObject.fromJSON')),
    [OBJ_TYPE_DIR]: raw => DirObject.fromJSON(asJsonObject(raw, 'DirObject.fromJSON')),
    [OBJ_TYPE_INCLUSION_PROOF]: raw =>
        InclusionProof.fromJSON(asJsonObject(raw, 'InclusionProof.fromJSON')),
    [OBJ_TYPE_RELATION]: raw =>
        RelationObject.fromJSON(asJsonObject(raw, 'RelationObject.fromJSON')),
    [OBJ_TYPE_CHUNK_LIST]: raw => SimpleChunkList.fromJsonValue(raw),
    [OBJ_TYPE_ACTION]: raw => plainObjectProducer(OBJ_TYPE_ACTION, actionObjectFromJson(raw)),
    [OBJ_TYPE_MSG]: raw => plainObjectProducer(OBJ_TYPE_MSG, msgObjectFromJsonChecked(raw)[0]),
    [OBJ_TYPE_RECEIPT]: raw => plainObjectProducer(OBJ_TYPE_RECEIPT, receiptObjFromJson(raw)),
    [OBJ_TYPE_PKG]: raw =>
        plainObjectProducer(
            OBJ_TYPE_PKG,
            normalizePackageMetaForObjId(asJsonObject(raw, 'PackageMeta')),
        ),
}

/**
 * Strict verification used by the test suite: run `raw` through the TS SDK
 * decoder for `objId.objType` (if one is registered), re-encode the decoded
 * instance via its `genObjId()` (which internally calls `toJSON()` +
 * canonical hash), and compare against `objId`.
 *
 * Behaviour:
 *   - registered type + clean round-trip → returns `true`
 *   - registered type + hash mismatch    → returns `false`
 *   - registered type + decode failure   → throws an Error tagged with the
 *                                          decode stage (caller sees the
 *                                          underlying NdnError message in
 *                                          the stack, jest prints it)
 *   - unregistered type                  → falls back to the SDK's
 *                                          shape-agnostic `verifyNamedObject`
 */
function verifyNamedObjectByDecode(objId: ObjId, raw: unknown): boolean {
    const decoder = TEST_NAMED_OBJECT_DECODERS[objId.objType]
    if (!decoder) {
        return verifyNamedObject(objId, raw)
    }
    let producer: ObjIdProducer
    try {
        producer = decoder(raw)
    } catch (e) {
        const msg = e instanceof Error ? e.message : String(e)
        throw new Error(
            `verifyNamedObjectByDecode: decode stage failed for ${objId.toString()}: ${msg}`,
        )
    }
    const [objId2] = producer.genObjId()
    return objId.equals(objId2)
}

export const defaultTap: Tap = {
    eq(actual, expected, msg) {
        if (actual !== expected) {
            throw new Error(
                `${msg ?? 'eq'}: expected ${fmt(expected)}, got ${fmt(actual)}`,
            )
        }
    },
    deepEq(actual, expected, msg) {
        if (!deepEqual(actual, expected)) {
            throw new Error(
                `${msg ?? 'deepEq'}: expected ${fmt(expected)}, got ${fmt(actual)}`,
            )
        }
    },
    truthy(value, msg) {
        if (!value) {
            throw new Error(`${msg ?? 'truthy'}: expected truthy, got ${fmt(value)}`)
        }
    },
    falsy(value, msg) {
        if (value) {
            throw new Error(`${msg ?? 'falsy'}: expected falsy, got ${fmt(value)}`)
        }
    },
    isNull(value, msg) {
        if (value !== null) {
            throw new Error(`${msg ?? 'isNull'}: expected null, got ${fmt(value)}`)
        }
    },
    throws(fn, kind, msg) {
        let thrown: unknown = null
        try {
            fn()
        } catch (e) {
            thrown = e
        }
        if (thrown == null) {
            throw new Error(`${msg ?? 'throws'}: expected fn to throw`)
        }
        if (kind != null) {
            if (!(thrown instanceof NdnError)) {
                throw new Error(
                    `${msg ?? 'throws'}: expected NdnError(${kind}), got ${
                        (thrown as Error)?.message ?? String(thrown)
                    }`,
                )
            }
            if (thrown.kind !== kind) {
                throw new Error(
                    `${msg ?? 'throws'}: expected NdnError kind=${kind}, got kind=${thrown.kind}`,
                )
            }
        }
    },
}

