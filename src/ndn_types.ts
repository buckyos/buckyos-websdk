export class SimpleChunkList {
    public total_size: number
    public body: ChunkId[]

    constructor() {
        this.total_size = 0
        this.body = []
    }

    static fromChunkList(chunks: ChunkId[]): SimpleChunkList {
        const list = new SimpleChunkList()
        for (const c of chunks) {
            const len = c.getLength()
            if (len == null) {
                throw new NdnError('InvalidParam', 'get chunk length from chunkid failed')
            }
            list.total_size += len
        }
        list.body = chunks.slice()
        return list
    }

    static fromJson(objStr: string): SimpleChunkList {
        let parsed: unknown
        try {
            parsed = JSON.parse(objStr)
        } catch (e) {
            throw new NdnError(
                'InvalidParam',
                `parse chunk list from json failed: ${(e as Error).message}`,
            )
        }
        return SimpleChunkList.fromJsonValue(parsed)
    }

    static fromJsonValue(value: unknown): SimpleChunkList {
        if (!Array.isArray(value)) {
            throw new NdnError('InvalidParam', 'chunk list must be a JSON array')
        }
        const chunks = value.map(item => {
            if (typeof item !== 'string') {
                throw new NdnError('InvalidParam', 'chunk list item must be a string')
            }
            return ChunkId.fromString(item)
        })
        return SimpleChunkList.fromChunkList(chunks)
    }

    appendChunk(chunkId: ChunkId): void {
        const len = chunkId.getLength()
        if (len == null) {
            throw new NdnError('InvalidParam', 'get chunk length from chunkid failed')
        }
        this.body.push(chunkId)
        this.total_size += len
    }

    /**
     * Mirrors SimpleChunkList::gen_obj_id(): hash the JSON list of ChunkId
     * strings, then prefix the resulting hash bytes with varint(total_size)
     * to form the final ObjId.
     */
    genObjId(): [ObjId, string] {
        const bodyJson = this.body.map(c => c.toString())
        const [innerObjId, objStr] = buildNamedObjectByJson(
            OBJ_TYPE_CHUNK_LIST,
            bodyJson,
        )
        const mixed = ChunkId.mixLengthAndHashResult(this.total_size, innerObjId.objHash)
        const resultId = ObjId.fromRaw(OBJ_TYPE_CHUNK_LIST, mixed)
        return [resultId, objStr]
    }
}

// ============================================================
// RelationObject (from relation_obj.rs)
// ============================================================

export type ObjectLinkData =
    | { kind: 'sameAs'; target: ObjId }
    | { kind: 'partOf'; target: ObjId; range: { start: number; end: number } }

export class RelationObject extends NamedObjectBase {
    public source: ObjId
    public relation: string
    public target: ObjId
    public body: Record<string, unknown>
    public iat: number | null
    public exp: number | null

    constructor(
        source: ObjId,
        relation: string,
        target: ObjId,
        body: Record<string, unknown> = {},
    ) {
        super()
        this.source = source
        this.relation = relation
        this.target = target
        this.body = body
        this.iat = null
        this.exp = null
    }

    /**
     * Reconstruct a RelationObject from its JSON form. `source`, `relation`,
     * `target`, `iat` and `exp` are reserved top-level fields; every other
     * key lands back in `body` (matching what `toJSON` spreads out), so the
     * decode → re-encode round-trip is byte-stable under canonical JSON
     * for any shape the TS class is capable of emitting.
     */
    static fromJSON(value: Record<string, unknown>): RelationObject {
        const reserved = new Set(['source', 'relation', 'target', 'iat', 'exp'])
        const body: Record<string, unknown> = {}
        for (const [k, v] of Object.entries(value)) {
            if (!reserved.has(k)) body[k] = v
        }
        const rel = new RelationObject(
            ObjId.fromString(String(value.source ?? '')),
            String(value.relation ?? ''),
            ObjId.fromString(String(value.target ?? '')),
            body,
        )
        rel.iat = typeof value.iat === 'number' ? value.iat : null
        rel.exp = typeof value.exp === 'number' ? value.exp : null
        return rel
    }

    static createByLinkData(source: ObjId, link: ObjectLinkData): RelationObject {
        switch (link.kind) {
            case 'sameAs':
                return new RelationObject(source, RELATION_TYPE_SAME, link.target)
            case 'partOf':
                return new RelationObject(
                    source,
                    RELATION_TYPE_PART_OF,
                    link.target,
                    { range: { start: link.range.start, end: link.range.end } },
                )
        }
    }

    getLinkData(): ObjectLinkData {
        switch (this.relation) {
            case RELATION_TYPE_SAME:
                return { kind: 'sameAs', target: this.target }
            case RELATION_TYPE_PART_OF: {
                const range = this.body.range as { start?: unknown; end?: unknown } | undefined
                if (!range || typeof range.start !== 'number' || typeof range.end !== 'number') {
                    throw new NdnError(
                        'InvalidLink',
                        `invalid range: ${JSON.stringify(this.body.range)}`,
                    )
                }
                return {
                    kind: 'partOf',
                    target: this.target,
                    range: { start: range.start, end: range.end },
                }
            }
            default:
                throw new NdnError('InvalidLink', `invalid relation: ${this.relation}`)
        }
    }

    getObjType(): string {
        return OBJ_TYPE_RELATION
    }

    toJSON(): Record<string, unknown> {
        const out: Record<string, unknown> = {
            source: this.source.toString(),
            relation: this.relation,
            target: this.target.toString(),
        }
        for (const [k, v] of Object.entries(this.body)) {
            out[k] = v
        }
        if (this.iat != null) out.iat = this.iat
        if (this.exp != null) out.exp = this.exp
        return out
    }
}

// ============================================================
// Strict decoding helpers: serde rules of the Rust structs
// ============================================================
//
// Used by the `*FromJson` functions. Optional fields follow `Option<T>`:
// missing and `null` both mean absent, so a `null` input re-serializes without
// the key. Unknown keys of nested structs are dropped, as serde does.

function decodeError(field: string, expected: string): NdnError {
    return new NdnError('DecodeError', `${field} must be ${expected}`)
}

function decodeRecord(value: unknown, field: string): Record<string, unknown> {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) {
        throw decodeError(field, 'an object')
    }
    return value as Record<string, unknown>
}

function decodeString(value: unknown, field: string): string {
    if (typeof value !== 'string') throw decodeError(field, 'a string')
    return value
}

/**
 * u64 in Rust, but JSON.parse loses precision above 2^53 and would produce a
 * wrong ObjId, so an unsafe integer is an error here rather than a silent
 * rounding.
 */
function decodeU64(value: unknown, field: string): number {
    if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0) {
        throw decodeError(field, 'a non-negative safe integer')
    }
    return value
}

function decodeObjIdString(value: unknown, field: string): string {
    const text = decodeString(value, field)
    try {
        return ObjId.fromString(text).toString()
    } catch (e) {
        throw decodeError(field, `an ObjId (${(e as Error).message})`)
    }
}

/** `did:method:id`. Rust also takes a host name, but it re-serializes differently. */
function decodeDid(value: unknown, field: string): string {
    const text = decodeString(value, field)
    const parts = text.split(':')
    if (parts.length < 3 || parts[0] !== 'did') throw decodeError(field, 'a did:method:id')
    return text
}

function decodeOneOf<T extends string>(values: readonly T[], value: unknown, field: string): T {
    if (typeof value !== 'string' || !(values as readonly string[]).includes(value)) {
        throw decodeError(field, `one of ${values.join(', ')}`)
    }
    return value as T
}

function decodeArray<T>(
    value: unknown,
    field: string,
    decode: (item: unknown, field: string) => T,
): T[] {
    if (!Array.isArray(value)) throw decodeError(field, 'an array')
    return value.map((item, index) => decode(item, `${field}[${index}]`))
}

function decodeOptional<T>(
    value: unknown,
    field: string,
    decode: (value: unknown, field: string) => T,
): T | undefined {
    return value === undefined || value === null ? undefined : decode(value, field)
}

function omitUndefined<T extends object>(value: T): T {
    const out: Record<string, unknown> = {}
    for (const [key, item] of Object.entries(value)) {
        if (item !== undefined) setOwnJsonField(out, key, item)
    }
    return out as T
}

