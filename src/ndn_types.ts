export function sha256Bytes(data: Uint8Array): Uint8Array {
    const sha = new jsSHA('SHA-256', 'UINT8ARRAY')
    sha.update(data)
    return sha.getHash('UINT8ARRAY')
}

export function sha256Utf8(text: string): Uint8Array {
    const sha = new jsSHA('SHA-256', 'TEXT', { encoding: 'UTF8' })
    sha.update(text)
    return sha.getHash('UINT8ARRAY')
}

function ensureValidJcsString(value: string): void {
    for (let i = 0; i < value.length; i++) {
        const code = value.charCodeAt(i)
        if (code < 0xd800 || code > 0xdfff) continue
        if (code <= 0xdbff) {
            const next = value.charCodeAt(i + 1)
            if (i + 1 < value.length && next >= 0xdc00 && next <= 0xdfff) {
                i++
                continue
            }
        }
        throw new NdnError('InvalidData', 'JSON string contains lone surrogate')
    }
}

function assertValidJcsPrimitive(value: unknown): void {
    switch (typeof value) {
        case 'string':
            ensureValidJcsString(value)
            return
        case 'number':
            if (!Number.isFinite(value)) {
                throw new NdnError('InvalidData', 'JSON number MUST be finite for JCS')
            }
            if (Object.is(value, -0)) {
                throw new NdnError('InvalidData', 'JSON number MUST NOT be negative zero for JCS')
            }
            return
        case 'boolean':
            return
        case 'undefined':
            throw new NdnError('InvalidData', 'undefined is not a valid JSON value')
        case 'bigint':
            throw new NdnError('InvalidData', 'bigint is not a valid JSON value')
        case 'function':
            throw new NdnError('InvalidData', 'function is not a valid JSON value')
        case 'symbol':
            throw new NdnError('InvalidData', 'symbol is not a valid JSON value')
        case 'object':
            if (value === null) return
            return
    }
}

// A plain assignment to `__proto__` would change the prototype and drop the
// key, so the ObjId of a JSON value carrying it would differ from Rust's.
function setOwnJsonField(target: Record<string, unknown>, key: string, value: unknown): void {
    if (key === '__proto__') {
        Object.defineProperty(target, key, { value, enumerable: true, writable: true, configurable: true })
    } else {
        target[key] = value
    }
}

/**
 * Recursively sort object keys (BTreeMap-like) while validating that the
 * value is representable as I-JSON/JCS input. Arrays preserve order.
 */
export function canonicalizeJson(value: any): any {
    assertValidJcsPrimitive(value)
    if (value === null || typeof value !== 'object') return value
    if (Array.isArray(value)) {
        const result = new Array(value.length)
        for (let i = 0; i < value.length; i++) {
            if (!Object.prototype.hasOwnProperty.call(value, i)) {
                throw new NdnError('InvalidData', 'sparse arrays are not valid JSON values')
            }
            result[i] = canonicalizeJson(value[i])
        }
        return result
    }
    const keys = Object.keys(value).sort()
    const result: Record<string, any> = {}
    for (const k of keys) {
        ensureValidJcsString(k)
        setOwnJsonField(result, k, canonicalizeJson(value[k]))
    }
    return result
}

export function toCanonicalJsonString(value: any): string {
    const normalized = canonicalizeJson(value)
    const result = canonicalize(normalized)
    if (result === undefined) {
        throw new NdnError('InvalidData', 'failed to canonicalize JSON value')
    }
    return result
}

